import os
import requests
from bs4 import BeautifulSoup
URL = "https://getautoseo.com/"

page = requests.get(URL, timeout=20)
page.raise_for_status()

soup = BeautifulSoup(page.text, "html.parser")

text = soup.get_text(" ", strip=True)

print(text[:5000])

api_key = os.environ["OPENROUTER_API_KEY"]

prompt = f"""
Проанализируй компанию по тексту её сайта.

Сайт:
{URL}

Текст сайта:
{text}

Верни результат СТРОГО в формате JSON.

Структура JSON:

{{
  "company": {{
    "name": "",
    "website": "",
    "description": ""
  }},
  "products_and_services": [],
"customer_examples": [],
"use_cases": [],
  "icp": {{
    "industries": [],
    "company_types": [],
    "company_size": [],
    "geography": [],
    "characteristics": []
  }},
  "buyer_roles": [],
  "market": [],
  "evidence": [],
  "hypotheses": []
}}

Правила:

1. Используй только информацию из текста сайта.

2. Главная задача — определить, ЧТО САМА АНАЛИЗИРУЕМАЯ КОМПАНИЯ ПРОДАЁТ, КОМУ она это продаёт и КАКУЮ ЗАДАЧУ клиента решает.

3. При определении продуктов и услуг в первую очередь учитывай:
   - название компании и описание на главной странице;
   - пункты основного меню;
   - страницы Products / Services / Pricing;
   - прямые коммерческие предложения;
   - описание функций продукта;
   - условия покупки, подписки или заказа.

4. В "products_and_services" помещай ТОЛЬКО продукты и услуги, которые сама анализируемая компания непосредственно предлагает или продаёт.

5. Не считай самостоятельным продуктом или услугой то, что встречается только:
   - в блоге;
   - в статье;
   - в демонстрационном материале;
   - в примере;
   - в кейсе клиента;
   - в отзывах;
   - в исследовании;
   - в упоминании стороннего сервиса;
   - в названии компании-партнёра;
   - в тексте, который компания использует как пример работы своего продукта.

6. Если продукт или услуга упоминается только в одном из перечисленных выше источников и нет явного подтверждения, что компания сама его продаёт, НЕ добавляй его в "products_and_services".

7. Статьи и другие материалы сайта НЕ могут сами по себе создавать новый продукт, услугу, отрасль или целевой сегмент компании.

8. Например, если компания публикует статью "Как выбрать промышленный компрессор", это НЕ означает, что компания продаёт компрессоры или работает с производителями компрессоров.

9. В "customer_examples" помещай только компании или людей, которые на сайте явно представлены как клиенты, пользователи, заказчики или участники case study.

10. Если компания просто упоминается в статье, примере, исследовании, партнёрском материале или демонстрации, НЕ считай её клиентом.

11. В "use_cases" описывай только реальные задачи клиентов, которые решаются подтверждёнными продуктами или услугами анализируемой компании.

12. Не превращай тему статьи, кейса или демонстрационного материала в отдельный use case, если нет связи с непосредственно продаваемым продуктом.

13. В "icp" указывай только характеристики потенциального клиента, которые подтверждаются коммерческим предложением компании, описанием продукта, кейсами клиентов или явно указанными целевыми сегментами.

14. Если отрасль встречается только в статье или демонстрационном контенте, НЕ добавляй её в ICP автоматически.

15. Если характеристика потенциального клиента является логическим выводом, а не прямым фактом сайта, помещай её в "hypotheses", а не в "icp".

16. В "buyer_roles" указывай должности людей, которые МОГУТ принимать решение о покупке подтверждённого продукта или услуги. Не утверждай конкретного ЛПР без подтверждения.

17. В "evidence" указывай конкретные факты из сайта, подтверждающие выводы.

18. В "hypotheses" помещай только выводы, которые являются предположениями.

19. Не придумывай факты, которых нет в тексте.

20. Если информации недостаточно, оставляй соответствующий массив пустым.

21. Лучше вернуть меньше продуктов, отраслей и use cases, чем добавить неподтверждённые.

22. Верни ТОЛЬКО JSON без пояснений, Markdown и ```.

23. Ответ должен быть валидным JSON.
24. Если объект обозначен как "пример статьи", "пример контента", "example article", "sample", "демонстрация" или аналогичным образом, НЕ добавляй его в "customer_examples", если нет отдельного подтверждения, что это клиент.
25. Отзывы Trustpilot сами по себе подтверждают наличие пользователя или автора отзыва, но не подтверждают размер компании, отрасль или статус корпоративного клиента, если это прямо не указано.
"""

response = requests.post(
    "https://openrouter.ai/api/v1/chat/completions",
    headers={
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    },
    json={
        "model": "inclusionai/ling-3.0-flash-fin:free",
        "messages": [
            {
                "role": "user",
                "content": prompt
            }
        ],
    },
    timeout=60,
)

response.raise_for_status()

import json
import re

result = response.json()

content = result["choices"][0]["message"]["content"]

content = re.sub(r"^```json\s*", "", content.strip())
content = re.sub(r"\s*```$", "", content)

data = json.loads(content)

print(json.dumps(data, ensure_ascii=False, indent=2))
